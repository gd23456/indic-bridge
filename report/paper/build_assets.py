# ------------------------------------------------------------------ Figure: gains
def gains_figure():
    plt.rcParams.update({"font.family": "serif", "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
                         "font.size": 7.5, "pdf.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.spines.left": False, "axes.edgecolor": "#888888", "xtick.color": "#333333", "ytick.color": "#111111"})
    HI, EN, GRID = "#985a0e", "#2a69ac", "#dddddd"
    g = gains[gains.metric == "WER"]
    fig, axes = plt.subplots(1, 2, figsize=(3.45, 1.9), sharey=True, sharex=True)
    for ax, ts in zip(axes, TS):
        for i, t in enumerate(TARGETS):
            for k, (key, colour, label) in enumerate([("hindi_pivot_gain", HI, "Hindi pivot"), ("english_pivot_gain", EN, "English pivot")]):
                r = g[(g.language == t) & (g.test_set == ts) & (g.gain == key)].iloc[0]
                y = i + (-0.16 if k == 0 else 0.16)
                ax.plot([r.ci_low, r.ci_high], [y, y], color=colour, lw=1.4, solid_capstyle="round")
                ax.plot(r.points, y, "o", ms=4.2, color=colour, mec="white", mew=0.8, label=label if i == 0 else None)
        ax.axvline(0, color="#555555", lw=0.7)
        ax.grid(axis="x", color=GRID, lw=0.5)
        ax.set_axisbelow(True)
        ax.set_title(TS[ts], fontsize=8, loc="left", fontweight="bold")
        ax.tick_params(axis="y", length=0)
        ax.set_xlabel("WER points saved vs direct", fontsize=7)
    axes[0].set_yticks(range(3), [NAME[t] for t in TARGETS])
    axes[0].invert_yaxis()
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.legend(*axes[0].get_legend_handles_labels(), loc="lower center", bbox_to_anchor=(0.55, -0.02), ncol=2, frameon=False, fontsize=7)
    fig.savefig(f"{OUT}/figures/fig_gains.pdf", bbox_inches="tight")
    fig.savefig(f"{OUT}/figures/fig_gains.png", dpi=300, bbox_inches="tight")
    plt.close(fig)
    print("wrote", f"{OUT}/figures/fig_gains.pdf")


