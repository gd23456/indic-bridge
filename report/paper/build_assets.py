TARGETS = ["marathi", "odia", "kannada"]


def row(run_id, test_set):
    r = master[(master.run_id == run_id) & (master.test_set == test_set)]
    return None if r.empty else r.iloc[0]


from decimal import ROUND_HALF_UP, Decimal  # noqa: E402


def r1(v):
    # Round half up from the stored decimal (74.85 -> 74.9), not from the binary float (74.8499...)
    return Decimal(repr(float(v))).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)


def f1(v):
    return f"{r1(v)}"


def sgn(v):
    q = r1(v)
    return f"{'+' if q > 0 else '$-$' if q < 0 else ''}{abs(q)}"


def plain(v):
    q = r1(v)
    return f"{'$-$' if q < 0 else ''}{abs(q)}"


def ci_cell(points, lo, hi, bold=False):
    head = f"\\textbf{{{sgn(points)}}}" if bold else sgn(points)
    return f"{head} [{plain(lo)}, {plain(hi)}]"


def write(name, body):
    with open(f"{OUT}/tables/{name}.tex", "w") as fh:
        fh.write("% Generated by report/paper/build_assets.py from results/. Do not edit numbers by hand.\n" + body)
    print("wrote", f"{OUT}/tables/{name}.tex")


# ---------------------------------------------------------------- Table: setup
