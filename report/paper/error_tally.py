"""
error_tally.py - turn the native-speaker annotations into the paper's error table.

    .venv/bin/python report/paper/error_tally.py

Reads results/error_analysis/<language>_50.csv (the direct_errors / multistage_errors columns,
categories separated by '|') and writes report/paper/tables/errors.tex: for each language and
category, how many of the 50 clips carry that error before and after the Hindi pivot. Prints how
many rows each annotator has filled, so a half-finished sheet is never reported as complete.
"""
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
CATS = ["SCRIPT", "PHONETIC", "MORPHOLOGY", "SEGMENTATION", "CODE_SWITCH", "NUMBER", "HALLUCINATION", "REFERENCE_WRONG"]
LANGS = [("hindi", "Hi"), ("marathi", "Mr"), ("odia", "Or"), ("kannada", "Kn")]


def cats(cell):
    return {c.strip().upper() for c in str(cell).split("|") if c.strip() and str(cell) != "nan"}


counts, filled = {}, {}
for lang, _ in LANGS:
    d = pd.read_csv(f"results/error_analysis/{lang}_50.csv", encoding="utf-8-sig", dtype=str)
    before, after = d["direct_errors"].map(cats), d["multistage_errors"].map(cats)
    done = (before.map(len) > 0) | (after.map(len) > 0)
    filled[lang] = int(done.sum())
    unknown = set().union(*before, *after) - set(CATS)
    if unknown:
        print(f"{lang}: unknown category codes {sorted(unknown)}; fix the spelling in the CSV")
    counts[lang] = {c: (int(before.map(lambda s: c in s).sum()), int(after.map(lambda s: c in s).sum())) for c in CATS}
    print(f"{lang}: {filled[lang]} of {len(d)} rows annotated")

if not any(filled.values()):
    raise SystemExit("No annotations yet: nothing written.")

body = ("% Generated by report/paper/error_tally.py from results/error_analysis/. Do not edit numbers by hand.\n"
        "\\begin{table}[!t]\n\\caption{Native-Speaker Error Categories: Clips (of 50 per Language) Showing Each Error, "
        "Before $\\rightarrow$ After the Hindi Pivot}\n\\label{tab:errors}\n\\centering\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n"
        "\\begin{tabular}{@{}l" + "c" * len(LANGS) + "@{}}\n\\hline\nCategory & " +
        " & ".join(f"{code}$^{{*}}$" if lang == "hindi" else code for lang, code in LANGS) + "\\\\\n\\hline\n")
for c in CATS:
    body += c.replace("_", "\\_").title().replace("\\_", " ") + " & " + " & ".join(
        f"{counts[l][c][0]} $\\rightarrow$ {counts[l][c][1]}" for l, _ in LANGS) + "\\\\\n"
body += ("\\hline\nAnnotated rows & " + " & ".join(str(filled[l]) for l, _ in LANGS) + "\\\\\n\\hline\n"
         "\\multicolumn{" + str(len(LANGS) + 1) + "}{@{}l}{$^{*}$Hindi: zero-shot $\\rightarrow$ fine-tuned pivot.}\\\\\n"
         "\\end{tabular}\n\\end{table}\n")
os.makedirs("report/paper/tables", exist_ok=True)
open("report/paper/tables/errors.tex", "w").write(body)
print("wrote report/paper/tables/errors.tex")
